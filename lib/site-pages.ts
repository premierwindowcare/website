export function citySlug(city: string) {
  return `${city.toLowerCase().replace(/\s+/g, "-")}-mi`
}

export function cityHref(city: string) {
  return `/${citySlug(city)}`
}

export function getLocationPage(slug: string) {
  const city = serviceCities.find((item) => citySlug(item) === slug)

  if (!city) {
    return null
  }

  const content = locationPages[city]

  return {
    city,
    slug,
    title: `Window Cleaning in ${city}, MI`,
    metaTitle: `Window Cleaning in ${city}, MI | Premier Window Care`,
    metaDescription: `${content.heroIntro} Request a free quote for window cleaning in ${city}, MI.`,
    ...content,
    icon: MapPin,
  }
}

